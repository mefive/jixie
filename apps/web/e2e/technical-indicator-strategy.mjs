  'let lastTarget = -1;',
  '',
  'export default defineStrategy({',
  "  name: '五指标趋势评分策略',",
  '  params: { adxPeriod: 14, bandPeriod: 20, rsiPeriod: 14 },',
  "  watch: ['600519.SH'],",
  '  onBar(ctx) {',
  "    const code = '600519.SH';",
  '    const directional = ctx.adx(code, ctx.params.adxPeriod);',
  '    const bands = ctx.bollingerBands(code, ctx.params.bandPeriod, 2);',
  '    const strength = ctx.rsi(code, ctx.params.rsiPeriod);',
  '    const convergence = ctx.macd(code, 12, 26, 9);',
  '    const stochastic = ctx.kdj(code, 9, 3, 3);',
  '    const price = ctx.price(code);',
  '',
  '    if (',
  '      directional == null ||',
  '      bands == null ||',
  '      strength == null ||',
  '      convergence == null ||',
  '      stochastic == null ||',
  '      price == null',
  '    ) {',
  '      return;',
  '    }',
  '',
  '    let score = 0;',
  '    if (directional.positiveDi > directional.negativeDi && directional.adx >= 20) {',
  '      score += 1;',
  '    }',
  '    if (price > bands.middle) {',
  '      score += 1;',
  '    }',
  '    if (strength >= 50) {',
  '      score += 1;',
  '    }',
  '    if (convergence.line > convergence.signal) {',
  '      score += 1;',
  '    }',
  '    if (stochastic.k > stochastic.d) {',
  '      score += 1;',
  '    }',
  '',
  '    const target = score >= 4 ? 0.6 : score === 3 ? 0.3 : 0;',
  '    if (target !== lastTarget) {',
  '      ctx.orderTargetPercent(code, target);',
  "      console.log('indicator-score', ctx.date, score, target);",
  '      lastTarget = target;',
  '    }',
  '  },',
  '});',
